const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const projectRoot = path.resolve(__dirname, "..");
const prismaDir = path.join(projectRoot, "prisma");
const prismaDb = path.join(prismaDir, "dev.db");
const rootDb = path.join(projectRoot, "dev.db");
const envProdPath = path.join(projectRoot, ".env.production");
const envPath = path.join(projectRoot, ".env");

console.log("[prepare-db] Preparing database and environment for build...");

try {
  if (!fs.existsSync(envPath)) {
    console.log("[prepare-db] Creating fallback .env for cloud build...");
    const fallbackEnv = `# Auto-generated by scripts/prepare-db.js for production build
DATABASE_URL="file:${prismaDb}"
SITE_URL="https://warmthplace.vercel.app"
SESSION_SECRET="70y5znky9Yv7PJnexV082JfCQ3uVRbryDvVN4RmjEYPsx8pWPq-X1MZ0fTKw6858"
NEXT_PUBLIC_SAMPLE_MODE="true"
STORE_CURRENCY="NGN"
PAYMENT_PROVIDER="mock"
`;
    fs.writeFileSync(envPath, fallbackEnv, "utf8");
  }

  // Ensure environment variable has absolute path fallback
  if (!process.env.DATABASE_URL) {
    process.env.DATABASE_URL = `file:${prismaDb}`;
  }

  // Check if database needs schema initialization
  const needsSchemaInit =
    !fs.existsSync(prismaDb) || fs.statSync(prismaDb).size < 2048;

  if (needsSchemaInit) {
    console.log("[prepare-db] Creating SQLite schema tables via prisma db push...");
    execSync("npx prisma db push --skip-generate --accept-data-loss", {
      cwd: projectRoot,
      stdio: "inherit",
      env: {
        ...process.env,
        DATABASE_URL: `file:${prismaDb}`,
      },
    });
  }

  // Generate Prisma client if needed
  try {
    execSync("npx prisma generate", {
      cwd: projectRoot,
      stdio: "inherit",
      env: {
        ...process.env,
        DATABASE_URL: `file:${prismaDb}`,
      },
    });
  } catch (genErr) {
    console.log("[prepare-db] Prisma client already generated or locked by dev server.");
  }

  console.log("[prepare-db] Database ready for Next.js build.");
} catch (err) {
  console.warn("[prepare-db] Non-fatal notice during database prep:", err.message);
}
